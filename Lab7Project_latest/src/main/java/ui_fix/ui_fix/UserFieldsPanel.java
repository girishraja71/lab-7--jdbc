    /** Copies the field values into the given user (id is not touched). */
    public void fillUser(User u) {
        u.setFirstName(txtFirstName.getText().trim());
        u.setLastName(txtLastName.getText().trim());
        u.setGender(rdoFemale.isSelected() ? "Female" : "Male");
        u.setDob(getDob());
        try {
            spnAge.commitEdit(); // saves a number typed into the spinner box
        } catch (java.text.ParseException ignored) {
            // not a valid number: keep the last valid value
        }
        u.setAge((Integer) spnAge.getValue());
        u.setPhone(txtPhone.getText().trim());
        u.setEmail(txtEmail.getText().trim());
        String continent = (String) cmbContinent.getSelectedItem();
        u.setContinent(SELECT_CONTINENT.equals(continent) ? null : continent);
        u.setExperience(txtExperience.getText().trim());
        u.setHobbies(txtHobbies.getText().trim());
        u.setPhotoPath(txtPhoto.getText().trim());
    }

    /** Shows a user's values in the fields. */
    public void showUser(User u) {
        txtFirstName.setText(u.getFirstName());
        txtLastName.setText(u.getLastName());
        if ("Female".equalsIgnoreCase(u.getGender())) {
            rdoFemale.setSelected(true);
        } else {
            rdoMale.setSelected(true);
        }
        setDob(u.getDob());
        spnAge.setValue(Math.max(1, Math.min(120, u.getAge())));
        txtPhone.setText(u.getPhone());
        txtEmail.setText(u.getEmail());
        cmbContinent.setSelectedItem(u.getContinent());
        txtExperience.setText(u.getExperience());
        txtHobbies.setText(u.getHobbies());
        txtPhoto.setText(u.getPhotoPath());
        showPhoto(u.getPhotoPath());
    }

    public void clear() {
        txtFirstName.setText("");
        txtLastName.setText("");
        rdoMale.setSelected(true);
        setDob(LocalDate.now().minusYears(18));
        spnAge.setValue(18);
        txtPhone.setText("");
        txtEmail.setText("");
        cmbContinent.setSelectedIndex(0);
        txtExperience.setText("");
        txtHobbies.setText("");
        txtPhoto.setText("");
        showPhoto(null);
    }

