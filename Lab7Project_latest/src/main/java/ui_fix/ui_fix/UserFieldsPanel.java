    /** Lab 4 style pop-up: the photo on the left and all the user's details on the right. */
    public static void showDetailsPopup(Component parent, String title, User u) {
        ImageIcon icon = null;
        String path = u.getPhotoPath();
        if (path != null && !path.isBlank() && new File(path).exists()) {
            Image img = new ImageIcon(path).getImage().getScaledInstance(150, 150, Image.SCALE_SMOOTH);
            icon = new ImageIcon(img);
        }
        String text = "<html><body style='font-size:12px'>"
                + "First Name: " + u.getFirstName() + "<br>"
                + "Last Name: " + u.getLastName() + "<br>"
                + "Gender: " + u.getGender() + "<br>"
                + "Date of Birth: " + u.getDob() + "<br>"
                + "Age: " + u.getAge() + "<br>"
                + "Phone: " + u.getPhone() + "<br>"
                + "Email: " + u.getEmail() + "<br>"
                + "Continent: " + u.getContinent() + "<br>"
                + "Experience: " + u.getExperience() + "<br>"
                + "Hobbies: " + u.getHobbies() + "<br>"
                + "Photo Path: " + (path == null || path.isBlank() ? "(none)" : path)
                + "</body></html>";
        JOptionPane.showMessageDialog(parent, text, title, JOptionPane.INFORMATION_MESSAGE, icon);
    }

