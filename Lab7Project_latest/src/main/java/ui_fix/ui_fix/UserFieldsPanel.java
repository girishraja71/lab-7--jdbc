    // ---------- Date of birth helpers ----------

    private void onDateChanged(boolean monthOrYearChanged) {
        if (loading) {
            return;
        }
        if (monthOrYearChanged) {
            Integer day = (Integer) cmbDay.getSelectedItem();
            refreshDays(day == null ? 1 : day);
        }
        // Fill in the age automatically from the chosen date
        LocalDate dob = getDob();
        if (dob != null && !dob.isAfter(LocalDate.now())) {
            int age = Period.between(dob, LocalDate.now()).getYears();
            spnAge.setValue(Math.max(1, Math.min(120, age)));
        }
    }

    /** Rebuilds the Day list for the selected month/year, keeping the chosen day if possible. */
    private void refreshDays(int keepDay) {
        boolean wasLoading = loading;
        loading = true;
        int month = cmbMonth.getSelectedIndex() + 1;
        Integer year = (Integer) cmbYear.getSelectedItem();
        int daysInMonth = YearMonth.of(year == null ? 2000 : year, Math.max(1, month)).lengthOfMonth();
        DefaultComboBoxModel<Integer> days = new DefaultComboBoxModel<>();
        for (int d = 1; d <= daysInMonth; d++) {
            days.addElement(d);
        }
        cmbDay.setModel(days);
        cmbDay.setSelectedItem(Math.min(keepDay, daysInMonth));
        loading = wasLoading;
    }

    private LocalDate getDob() {
        Integer day = (Integer) cmbDay.getSelectedItem();
        Integer year = (Integer) cmbYear.getSelectedItem();
        if (day == null || year == null || cmbMonth.getSelectedIndex() < 0) {
            return null;
        }
        return LocalDate.of(year, cmbMonth.getSelectedIndex() + 1, day);
    }

    private void setDob(LocalDate dob) {
        loading = true;
        cmbYear.setSelectedItem(dob.getYear());
        cmbMonth.setSelectedIndex(dob.getMonthValue() - 1);
        refreshDays(dob.getDayOfMonth());
        loading = false;
    }

    // ---------- Photo helper ----------

    private void showPhoto(String path) {
        if (path == null || path.isBlank() || !new File(path).exists()) {
            lblPhotoPreview.setIcon(null);
            lblPhotoPreview.setText("No photo");
            return;
        }
        Image img = new ImageIcon(path).getImage().getScaledInstance(110, 110, Image.SCALE_SMOOTH);
        lblPhotoPreview.setText("");
        lblPhotoPreview.setIcon(new ImageIcon(img));
    }

