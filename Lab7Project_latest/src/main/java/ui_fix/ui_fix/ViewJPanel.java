    // EDIT unlocks the fields. While editing the button says CANCEL, which puts the old values back.
    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (selectedUser == null) {
            return;
        }
        if (editing) {
            fields.showUser(selectedUser); // undo any changes
            fields.setFieldsEnabled(false);
            editing = false;
        } else {
            fields.setFieldsEnabled(true);
            editing = true;
        }
        updateButtons();
    }//GEN-LAST:event_btnEditActionPerformed

    // UPDATE: save the changed fields to the database
    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedUser == null || !editing) {
            return;
        }
        try {
            User edited = new User();
            edited.setId(selectedUser.getId());
            fields.fillUser(edited);

            String error = InputValidator.validate(edited);
            if (error != null) {
                JOptionPane.showMessageDialog(this, error, "Input Error", JOptionPane.WARNING_MESSAGE);
                return;
            }
            DatabaseConnector.editUser(edited);
            UserFieldsPanel.showDetailsPopup(this, "Success - user updated", edited);

            populateTable();
            selectRowById(edited.getId()); // keep the same user selected
        } catch (SQLException ex) {
            if (DatabaseConnector.isDuplicateEmail(ex)) {
                JOptionPane.showMessageDialog(this, "That email is already registered to another user.",
                        "Input Error", JOptionPane.ERROR_MESSAGE);
            } else {
                showError(ex);
            }
        } catch (Exception ex) {
            showError(ex);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    // DELETE: remove the selected user from the database
    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedUser == null || editing) {
            return;
        }
        int choice = JOptionPane.showConfirmDialog(this,
                "Delete " + selectedUser.getFirstName() + " " + selectedUser.getLastName() + "?",
                "Confirm Delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            DatabaseConnector.deleteUser(selectedUser.getId());
            JOptionPane.showMessageDialog(this, "User deleted.");
            populateTable();
        } catch (Exception ex) {
            showError(ex);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    // Double-click a row to see all the details with the photo (like Lab 4)
    private void tblUsersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsersMouseClicked
        if (evt.getClickCount() == 2 && selectedUser != null && !editing) {
            UserFieldsPanel.showDetailsPopup(this, "User Details", selectedUser);
        }
    }//GEN-LAST:event_tblUsersMouseClicked

    /** Turns the buttons on/off to match what the user is doing right now. */
    private void updateButtons() {
        boolean rowSelected = selectedUser != null;
        btnEdit.setText(editing ? "Cancel" : "Edit");
        btnEdit.setEnabled(rowSelected);
        btnUpdate.setEnabled(rowSelected && editing);
        btnDelete.setEnabled(rowSelected && !editing);
    }

    // READ: load every row from the database into the JTable
    private void populateTable() {
        try {
            users = DatabaseConnector.getAllUsers();
            tableModel.setRowCount(0);
            for (User u : users) {
                tableModel.addRow(new Object[]{u.getId(), u.getFirstName(), u.getLastName(),
                    u.getAge(), u.getEmail(), u.getContinent()});
            }
        } catch (Exception ex) {
            showError(ex);
        }
    }

    /** Selects the table row of the user with this id (used after Update). */
    private void selectRowById(int id) {
        for (int i = 0; i < users.size(); i++) {
            if (users.get(i).getId() == id) {
                int viewRow = tblUsers.convertRowIndexToView(i);
                tblUsers.setRowSelectionInterval(viewRow, viewRow);
                tblUsers.scrollRectToVisible(tblUsers.getCellRect(viewRow, 0, true));
                return;
            }
        }
    }

    // When a row is clicked, show that user's details on the left (read-only)
    private void onRowSelected() {
        try {
            int row = tblUsers.getSelectedRow();
            editing = false;
            if (row < 0) {
                selectedUser = null;
                fields.clear();
            } else {
                selectedUser = users.get(tblUsers.convertRowIndexToModel(row));
                fields.showUser(selectedUser);
            }
            fields.setFieldsEnabled(false);
            updateButtons();
        } catch (Exception ex) {
            showError(ex);
        }
    }

    private void showError(Exception ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + ex, "Error", JOptionPane.ERROR_MESSAGE);
    }

