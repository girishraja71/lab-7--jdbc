    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        try {
            User user = new User();
            fields.fillUser(user);

            String error = InputValidator.validate(user);
            if (error != null) {
                JOptionPane.showMessageDialog(this, error, "Input Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            DatabaseConnector.addUser(user);
            // Lab 4 style success pop-up with the photo and all the details
            UserFieldsPanel.showDetailsPopup(this, "Success - user saved to the database", user);
            fields.clear();

        } catch (SQLException ex) {
            if (DatabaseConnector.isDuplicateEmail(ex)) {
                JOptionPane.showMessageDialog(this, "That email is already registered. Please use a different email.",
                        "Input Error", JOptionPane.ERROR_MESSAGE);
            } else {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage(),
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error: " + ex, "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

